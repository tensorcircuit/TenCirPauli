/// Compatibility relation used by deterministic measurement grouping.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum GroupingMode {
    /// Qubit-wise commuting: every local pair is equal or contains identity.
    QubitWise,
    /// Algebraic commuting: the binary symplectic inner product is zero.
    General,
}

/// Deterministic graph-coloring strategy.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum GroupingAlgorithm {
    /// Order vertices by descending incompatibility degree.
    LargestFirst,
    /// Repeatedly choose the highest saturation-degree vertex.
    Dsatur,
}

/// Return a deterministic partition of input term indices into compatible groups.
pub fn group_words(
    words: &[PauliWord],
    mode: GroupingMode,
    algorithm: GroupingAlgorithm,
) -> Result<Vec<Vec<usize>>, PauliError> {
    if let Some(first) = words.first() {
        if let Some(other) = words.iter().find(|word| word.nqubits != first.nqubits) {
            return Err(PauliError::IncompatibleQubitCounts {
                left: first.nqubits,
                right: other.nqubits,
            });
        }
    }
    let size = words.len();
    let mut incompatible = vec![vec![false; size]; size];
    for left in 0..size {
        for right in (left + 1)..size {
            let compatible = match mode {
                GroupingMode::QubitWise => words[left].qwc_compatible(&words[right])?,
                GroupingMode::General => words[left].commutes_with(&words[right])?,
            };
            incompatible[left][right] = !compatible;
            incompatible[right][left] = !compatible;
        }
    }
    let mut groups: Vec<Vec<usize>> = Vec::new();
    if algorithm == GroupingAlgorithm::LargestFirst {
        let mut order: Vec<usize> = (0..size).collect();
        order.sort_by(|left, right| {
            degree(*right, &incompatible)
                .cmp(&degree(*left, &incompatible))
                .then_with(|| left.cmp(right))
        });
        for vertex in order {
            place_vertex(vertex, &incompatible, &mut groups);
        }
    } else {
        let mut colors = vec![None; size];
        for _ in 0..size {
            let vertex = (0..size)
                .filter(|index| colors[*index].is_none())
                .max_by(|left, right| {
                    saturation(*left, &incompatible, &colors)
                        .cmp(&saturation(*right, &incompatible, &colors))
                        .then_with(|| {
                            degree(*left, &incompatible).cmp(&degree(*right, &incompatible))
                        })
                        .then_with(|| right.cmp(left))
                })
                .expect("uncolored vertex exists for every DSATUR iteration");
            let mut color = 0;
            while colors
                .iter()
                .enumerate()
                .any(|(index, current)| *current == Some(color) && incompatible[vertex][index])
            {
                color += 1;
            }
            colors[vertex] = Some(color);
        }
        let max_color = colors.iter().flatten().copied().max().unwrap_or(0);
        groups = (0..=max_color).map(|_| Vec::new()).collect();
        for (vertex, color) in colors.into_iter().enumerate() {
            groups[color.expect("all DSATUR vertices are colored")].push(vertex);
        }
        groups.retain(|group| !group.is_empty());
    }
    for group in &mut groups {
        group.sort_unstable();
    }
    groups.sort_by_key(|group| group[0]);
    Ok(groups)
}

/// Build a bounded dense compatibility matrix for a batch of words.
pub fn compatibility_matrix(
    words: &[PauliWord],
    mode: GroupingMode,
    max_entries: usize,
) -> Result<Vec<bool>, PauliError> {
    let entries = words
        .len()
        .checked_mul(words.len())
        .ok_or(PauliError::Overflow {
            context: "estimating compatibility matrix entries",
        })?;
    if entries > max_entries {
        return Err(PauliError::MemoryLimit {
            requested: entries as u128,
            limit: max_entries as u128,
        });
    }
    let mut matrix = vec![false; entries];
    for left in 0..words.len() {
        for right in 0..words.len() {
            matrix[left * words.len() + right] = match mode {
                GroupingMode::QubitWise => words[left].qwc_compatible(&words[right])?,
                GroupingMode::General => words[left].commutes_with(&words[right])?,
            };
        }
    }
    Ok(matrix)
}

/// Build a bounded streaming incompatibility edge list without materializing
/// the dense matrix.
pub fn incompatibility_edges(
    words: &[PauliWord],
    mode: GroupingMode,
    max_edges: usize,
) -> Result<Vec<(usize, usize)>, PauliError> {
    let mut edges = Vec::new();
    for left in 0..words.len() {
        for right in (left + 1)..words.len() {
            let compatible = match mode {
                GroupingMode::QubitWise => words[left].qwc_compatible(&words[right])?,
                GroupingMode::General => words[left].commutes_with(&words[right])?,
            };
            if !compatible {
                if edges.len() >= max_edges {
                    return Err(PauliError::MemoryLimit {
                        requested: (edges.len() + 1) as u128,
                        limit: max_edges as u128,
                    });
                }
                edges.push((left, right));
            }
        }
    }
    Ok(edges)
}

fn degree(vertex: usize, incompatible: &[Vec<bool>]) -> usize {
    incompatible[vertex].iter().filter(|value| **value).count()
}

fn place_vertex(vertex: usize, incompatible: &[Vec<bool>], groups: &mut Vec<Vec<usize>>) {
    if let Some(group) = groups
        .iter_mut()
        .find(|group| group.iter().all(|other| !incompatible[vertex][*other]))
    {
        group.push(vertex);
    } else {
        groups.push(vec![vertex]);
    }
}

fn saturation(vertex: usize, incompatible: &[Vec<bool>], colors: &[Option<usize>]) -> usize {
    let mut seen = Vec::new();
    for (other, is_incompatible) in incompatible[vertex].iter().enumerate() {
        if *is_incompatible {
            if let Some(color) = colors[other] {
                if !seen.contains(&color) {
                    seen.push(color);
                }
            }
        }
    }
    seen.len()
}

impl PauliOperator {
    /// Construct an operator, aggregate duplicate words, sort by code tuple,
    /// and remove only exact-zero coefficients.
    pub fn from_terms(
        nqubits: usize,
        structures: &[Vec<u8>],
        coefficients: &[Complex64],
    ) -> Result<Self, PauliError> {
        if structures.len() != coefficients.len() {
            return Err(PauliError::InvalidStructureLength {
                expected: structures.len(),
                actual: coefficients.len(),
            });
        }
        let mut aggregate = BTreeMap::<PauliWord, Vec<Complex64>>::new();
        for (index, (structure, &coefficient)) in structures.iter().zip(coefficients).enumerate() {
            if !coefficient.re.is_finite() || !coefficient.im.is_finite() {
                return Err(PauliError::NonFiniteCoefficient { index });
            }
            let word = PauliWord::from_codes(nqubits, structure)?;
            aggregate.entry(word).or_default().push(coefficient);
        }
        let terms = aggregate
            .into_iter()
            .filter_map(|(word, mut coefficients)| {
                // Sort duplicate contributions by their IEEE bit patterns so
                // aggregation is independent of input order while retaining
                // the exact-zero policy.
                coefficients.sort_by_key(|value| (value.re.to_bits(), value.im.to_bits()));
                let coefficient = coefficients
                    .into_iter()
                    .fold(Complex64::default(), |sum, value| sum + value);
                (!coefficient.is_zero()).then_some(PauliTerm { word, coefficient })
            })
            .collect();
        Ok(Self { nqubits, terms })
    }

    /// Construct an empty operator on `nqubits`.
    pub fn empty(nqubits: usize) -> Self {
        Self {
            nqubits,
            terms: Vec::new(),
        }
    }

    /// Return the qubit count.
    pub fn nqubits(&self) -> usize {
        self.nqubits
    }

    /// Return canonical terms.
    pub fn terms(&self) -> &[PauliTerm] {
        &self.terms
    }

    /// Add two operators and canonicalize the result.
    pub fn add(&self, other: &Self) -> Result<Self, PauliError> {
        self.ensure_compatible(other)?;
        let mut structures = Vec::with_capacity(self.terms.len() + other.terms.len());
        let mut coefficients = Vec::with_capacity(structures.capacity());
        for term in self.terms.iter().chain(&other.terms) {
            structures.push(term.word.codes());
            coefficients.push(term.coefficient);
        }
        Self::from_terms(self.nqubits, &structures, &coefficients)
    }

    /// Scale all coefficients by a finite complex scalar.
    pub fn scale(&self, scalar: Complex64) -> Result<Self, PauliError> {
        if !scalar.re.is_finite() || !scalar.im.is_finite() {
            return Err(PauliError::NonFiniteCoefficient { index: 0 });
        }
        let mut result = self.clone();
        for term in &mut result.terms {
            term.coefficient *= scalar;
        }
        Ok(result)
    }

    /// Multiply two canonical operators with exact Pauli phases.
    pub fn multiply(&self, other: &Self) -> Result<Self, PauliError> {
        self.ensure_compatible(other)?;
        let mut structures = Vec::with_capacity(self.terms.len() * other.terms.len());
        let mut coefficients = Vec::with_capacity(structures.capacity());
        for left in &self.terms {
            for right in &other.terms {
                let (word, phase) = left.word.multiply(&right.word)?;
                structures.push(word.codes());
                coefficients.push(left.coefficient * right.coefficient * phase.as_complex());
            }
        }
        Self::from_terms(self.nqubits, &structures, &coefficients)
    }

    /// Compute `[self, other]`.
    pub fn commutator(&self, other: &Self) -> Result<Self, PauliError> {
        self.multiply(other)?
            .add(&other.multiply(self)?.scale(Complex64::new(-1.0, 0.0))?)
    }

    /// Compute `{self, other}`.
    pub fn anticommutator(&self, other: &Self) -> Result<Self, PauliError> {
        self.multiply(other)?.add(&other.multiply(self)?)
    }

    /// Return the adjoint operator.
    pub fn adjoint(&self) -> Self {
        Self {
            nqubits: self.nqubits,
            terms: self
                .terms
                .iter()
                .map(|term| PauliTerm {
                    word: term.word.adjoint(),
                    coefficient: term.coefficient.conj(),
                })
                .collect(),
        }
    }

    /// Check exact Hermiticity or Hermiticity within an explicit tolerance.
    pub fn is_hermitian(&self, tolerance: f64) -> bool {
        if !tolerance.is_finite() || tolerance < 0.0 {
            return false;
        }
        self.terms.iter().all(|term| {
            let difference = term.coefficient - term.coefficient.conj();
            difference.norm_sqr() <= tolerance * tolerance
        })
    }

    fn ensure_compatible(&self, other: &Self) -> Result<(), PauliError> {
        if self.nqubits != other.nqubits {
            return Err(PauliError::IncompatibleQubitCounts {
                left: self.nqubits,
                right: other.nqubits,
            });
        }
        Ok(())
    }

    /// Compile a dense row-major matrix using qubit zero as the MSB.
    pub fn dense_matrix(&self, max_bytes: u128) -> Result<(usize, Vec<Complex64>), PauliError> {
        let dimension = matrix_dimension(self.nqubits)?;
        let entries = dimension
            .checked_mul(dimension)
            .ok_or(PauliError::Overflow {
                context: "estimating dense matrix entries",
            })?;
        check_allocation(entries as u128 * 16, max_bytes)?;
        let mut matrix = vec![Complex64::default(); entries];
        for term in &self.terms {
            let x_mask = matrix_x_mask(&term.word)?;
            for column in 0..dimension {
                let row = column ^ x_mask;
                let phase = matrix_phase(&term.word, column);
                matrix[row * dimension + column] += term.coefficient * phase;
            }
        }
        Ok((dimension, matrix))
    }

    /// Compile deterministic, duplicate-aggregated COO entries.
    pub fn coo_matrix(&self, max_bytes: u128) -> Result<CooMatrix, PauliError> {
        let dimension = matrix_dimension(self.nqubits)?;
        let upper_bound = self
            .terms
            .len()
            .checked_mul(dimension)
            .ok_or(PauliError::Overflow {
                context: "estimating COO entries",
            })?;
        check_allocation(upper_bound as u128 * 40, max_bytes)?;
        let mut entries = BTreeMap::<(u64, u64), Complex64>::new();
        for term in &self.terms {
            let x_mask = matrix_x_mask(&term.word)?;
            for column in 0..dimension {
                let row = column ^ x_mask;
                let value = term.coefficient * matrix_phase(&term.word, column);
                entries
                    .entry((row as u64, column as u64))
                    .and_modify(|current| *current += value)
                    .or_insert(value);
            }
        }
        let mut rows = Vec::with_capacity(entries.len());
        let mut columns = Vec::with_capacity(entries.len());
        let mut values = Vec::with_capacity(entries.len());
        for ((row, column), value) in entries {
            if !value.is_zero() {
                rows.push(row);
                columns.push(column);
                values.push(value);
            }
        }
        Ok(CooMatrix {
            dimension,
            rows,
            columns,
            values,
        })
    }

    /// Compile deterministic CSR from the canonical COO stream.
    pub fn csr_matrix(&self, max_bytes: u128) -> Result<CsrMatrix, PauliError> {
        let coo = self.coo_matrix(max_bytes)?;
        let mut indptr = vec![0_u64; coo.dimension + 1];
        for &row in &coo.rows {
            indptr[row as usize + 1] += 1;
        }
        for row in 1..indptr.len() {
            indptr[row] += indptr[row - 1];
        }
        Ok(CsrMatrix {
            dimension: coo.dimension,
            indptr,
            columns: coo.columns,
            values: coo.values,
        })
    }

    /// Apply the operator without materializing a matrix.
    pub fn mvp(&self, state: &[Complex64], max_bytes: u128) -> Result<Vec<Complex64>, PauliError> {
        let dimension = matrix_dimension(self.nqubits)?;
        if state.len() != dimension {
            return Err(PauliError::InvalidStructureLength {
                expected: dimension,
                actual: state.len(),
            });
        }
        check_allocation(dimension as u128 * 16, max_bytes)?;
        let mut result = vec![Complex64::default(); dimension];
        for term in &self.terms {
            let x_mask = matrix_x_mask(&term.word)?;
            for (column, state_value) in state.iter().enumerate() {
                let row = column ^ x_mask;
                result[row] += term.coefficient * matrix_phase(&term.word, column) * *state_value;
            }
        }
        Ok(result)
    }

    /// Return a versioned pure-array backend MVP plan.
    pub fn backend_mvp_plan(&self, max_bytes: u128) -> Result<BackendMvpPlan, PauliError> {
        let word_count = packed_word_count(self.nqubits);
        let bytes = (self.terms.len() as u128)
            .checked_mul((word_count as u128).saturating_mul(16).saturating_add(16))
            .ok_or(PauliError::Overflow {
                context: "estimating backend plan bytes",
            })?;
        check_allocation(bytes, max_bytes)?;
        let mut x_words = Vec::with_capacity(self.terms.len() * word_count);
        let mut z_words = Vec::with_capacity(self.terms.len() * word_count);
        let mut coefficients = Vec::with_capacity(self.terms.len());
        for term in &self.terms {
            x_words.extend_from_slice(term.word.x_words());
            z_words.extend_from_slice(term.word.z_words());
            coefficients.push(term.coefficient);
        }
        Ok(BackendMvpPlan {
            nqubits: self.nqubits,
            word_count,
            x_words,
            z_words,
            coefficients,
        })
    }
}

fn matrix_dimension(nqubits: usize) -> Result<usize, PauliError> {
    if nqubits >= usize::BITS as usize {
        return Err(PauliError::Overflow {
            context: "computing matrix dimension",
        });
    }
    1_usize
        .checked_shl(nqubits as u32)
        .ok_or(PauliError::Overflow {
            context: "computing matrix dimension",
        })
}

fn check_allocation(requested: u128, limit: u128) -> Result<(), PauliError> {
    if requested > limit {
        return Err(PauliError::MemoryLimit { requested, limit });
    }
    Ok(())
}

fn matrix_x_mask(word: &PauliWord) -> Result<usize, PauliError> {
    if word.nqubits >= usize::BITS as usize {
        return Err(PauliError::Overflow {
            context: "converting matrix X mask",
        });
    }
    let mut mask = 0_usize;
    for (qubit, code) in word.codes().into_iter().enumerate() {
        if code == 1 || code == 2 {
            mask |= 1_usize << (word.nqubits - 1 - qubit);
        }
    }
    Ok(mask)
}

fn matrix_phase(word: &PauliWord, column: usize) -> Complex64 {
    let mut phase = Complex64::new(1.0, 0.0);
    for (qubit, code) in word.codes().into_iter().enumerate() {
        let bit = (column >> (word.nqubits - 1 - qubit)) & 1;
        match code {
            2 => {
                phase *= if bit == 0 {
                    Complex64::new(0.0, 1.0)
                } else {
                    Complex64::new(0.0, -1.0)
                };
            }
            3 if bit == 1 => phase *= -1.0,
            _ => {}
        }
    }
    phase
}

/// Convert a qubit count to a packed word count without integer overflow.
pub fn packed_word_count(nqubits: usize) -> usize {
    nqubits / 64 + usize::from(nqubits % 64 != 0)
}

fn final_word_mask(nqubits: usize) -> Option<u64> {
    let remainder = nqubits % 64;
    (remainder != 0).then(|| (1_u64 << remainder) - 1)
}

fn code_bits(code: u8, index: usize) -> Result<(u64, u64), PauliError> {
    match code {
        0 => Ok((0, 0)),
        1 => Ok((1, 0)),
        2 => Ok((1, 1)),
        3 => Ok((0, 1)),
        _ => Err(PauliError::InvalidCode { code, index }),
    }
}

fn local_product(left: u8, right: u8) -> (u8, PauliPhase) {
    match (left, right) {
        (0, code) | (code, 0) => (code, PauliPhase::PlusOne),
        (1, 1) | (2, 2) | (3, 3) => (0, PauliPhase::PlusOne),
        (1, 2) => (3, PauliPhase::PlusI),
        (2, 1) => (3, PauliPhase::MinusI),
        (1, 3) => (2, PauliPhase::MinusI),
        (3, 1) => (2, PauliPhase::PlusI),
        (2, 3) => (1, PauliPhase::PlusI),
        (3, 2) => (1, PauliPhase::MinusI),
        _ => unreachable!("PauliWord validates local codes before multiplication"),
    }
}

#[cfg(test)]
mod tests {
    use super::{Complex64, PauliOperator, PauliPhase, PauliWord};

    #[test]
    fn computes_weight_and_canonicalizes_unused_bits() {
        let word = PauliWord::from_words(2, vec![u64::MAX], vec![0]).unwrap();
        assert_eq!(word.x_words(), &[0b11]);
        assert_eq!(word.weight(), 2);
    }

    #[test]
    fn checks_symplectic_commutation() {
        let x0 = PauliWord::from_words(2, vec![0b01], vec![0]).unwrap();
        let z0 = PauliWord::from_words(2, vec![0], vec![0b01]).unwrap();
        let xx = PauliWord::from_words(2, vec![0b11], vec![0]).unwrap();
        let zz = PauliWord::from_words(2, vec![0], vec![0b11]).unwrap();
        assert!(!x0.commutes_with(&z0).unwrap());
        assert!(xx.commutes_with(&zz).unwrap());
    }

    #[test]
    fn covers_phase_table_and_round_trip() {
        let expected = [
            (1, 2, 3, PauliPhase::PlusI),
            (2, 1, 3, PauliPhase::MinusI),
            (1, 3, 2, PauliPhase::MinusI),
            (3, 1, 2, PauliPhase::PlusI),
            (2, 3, 1, PauliPhase::PlusI),
            (3, 2, 1, PauliPhase::MinusI),
        ];
        for (left, right, result, phase) in expected {
            let left_word = PauliWord::from_codes(1, &[left]).unwrap();
            let right_word = PauliWord::from_codes(1, &[right]).unwrap();
            let (actual, actual_phase) = left_word.multiply(&right_word).unwrap();
            assert_eq!(actual.codes(), vec![result]);
            assert_eq!(actual_phase, phase);
        }
        let word = PauliWord::from_codes(130, &[2; 130]).unwrap();
        assert_eq!(word.codes(), vec![2; 130]);
    }

    #[test]
    fn canonical_operator_algebra_aggregates_exact_zeros() {
        let operator = PauliOperator::from_terms(
            1,
            &[vec![1], vec![1], vec![2]],
            &[
                Complex64::new(1.0, 0.0),
                Complex64::new(-1.0, 0.0),
                Complex64::new(2.0, 0.0),
            ],
        )
        .unwrap();
        assert_eq!(operator.terms().len(), 1);
        assert!(operator.is_hermitian(0.0));
        let reversed = PauliOperator::from_terms(
            1,
            &[vec![2], vec![1], vec![1]],
            &[
                Complex64::new(2.0, 0.0),
                Complex64::new(-1.0, 0.0),
                Complex64::new(1.0, 0.0),
            ],
        )
        .unwrap();
        let reordered = PauliOperator::from_terms(
            1,
            &[vec![1], vec![2], vec![1]],
            &[
                Complex64::new(1.0, 0.0),
                Complex64::new(2.0, 0.0),
                Complex64::new(-1.0, 0.0),
            ],
        )
        .unwrap();
        assert_eq!(reversed, reordered);
    }
}
